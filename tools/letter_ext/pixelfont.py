ROWS = 9


def glyph(ch):
    rows = _G[ch]
    w = max(len(r) for r in rows if r)
    return [[c == '#' for c in (r or '.' * w)] for r in rows] + [[False] * w] * (ROWS - len(rows))


def width(text):
    return len(text_rows(text)[0])


def text_rows(text):
    out = [[] for _ in range(ROWS)]
    for k, ch in enumerate(text):
        if ch == ' ':
            for r in out:
                r.extend([False] * (WORD_GAP - LETTER_GAP))   # the letter gaps around it make WORD_GAP
            continue
        if ch not in _G:
            raise SystemExit(f'pixelfont: no glyph for {ch!r}')
        g = glyph(ch)
        if out[0]:
            for r in out:
                r.extend([False] * LETTER_GAP)
        for r, gr in zip(out, g):
            r.extend(gr)
    return out
