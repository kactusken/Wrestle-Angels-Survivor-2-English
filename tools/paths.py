"""Where everything lives. Every tool imports its paths from here.

Default layout, relative to the project folder (the folder that contains tools/):

    rom/                      the original image you provide (never modified, not in git)
    translation/              everything that is edited by hand
        script/               story/dialogue message blocks (.txt)
        text/                 menu strings: message blocks (.txt) and tables (.csv)
        fill/                 bulk-fill tables {"source": "English"} (*_en.py)
        glossary.csv          names and recurring terms (checked by tools/lint.py)
        graphics.csv          every image with text: original, English, status, hints
        renders.json          fingerprints of the automatic renders (written by tools/render.py)
        images-rendered/      automatic English renders, frozen (game art - not in git)
        images-approved/      finished images, frozen (game art - not in git)
        images-handmade/      hand edits in progress (game art - not in git)
    extracted/                unpacked game files from tools/extract.py
    build/                    build output; build/work/ for intermediates and ad-hoc scripts
    release/                  patches and zip from make_patches.py
    review/                   pictures to look at - regenerated by the tools
        images-original/      every original image (indexed PNG + .json for the importer)
        images-english/       every final image, exactly as in the last build
        compare/              original | English sheets
        contact-sheets/       every image with its id
        edit/                 reference images from edit.py
    screenshots/              emulator screenshots dropped in during testing
    tools/  docs/

Every location can be moved with the folder options below (see FOLDER_HELP); tools that use these
folders accept them on the command line. Relative paths are taken from the current directory.
"""
import argparse
import functools
import os
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
GAME = 'Wrestle Angels: Survivor 2'                           # used in output names and release notes
GAME_FILE = GAME.replace(':', ' -')   # GAME in file names: Windows doesn't allow ':'
PLATFORM = 'PS2'
ORIGINAL_NAME = 'Wrestle Angels Survivor 2 (Japan).iso'              # the original image, as dumped (Redump name)
SERIAL = 'SLPM-55056'                               # e.g. SLPM-65602 (SYSTEM.CNF): release notes, submissions
# The original the patches apply to (make_patches.py and build.py check it)
ORIGINAL = {'size': 4074340352, 'crc32': '275d9e6f', 'md5': '8432744a65e4064cdfc117d77e95131b', 'sha1': 'ea5d4f86102205b885e15a09b5e4d4318d839136'}

FOLDER_HELP = '''folder options (defaults are relative to --root, which defaults to the project folder):
  --root DIR          base folder for every default below
  --rom PATH          the original image, or a folder holding it    (rom/)
  --translation DIR   script/, text/, graphics.csv, images-*/    (translation/)
  --extracted DIR     unpacked game files    (extracted/)
  --build DIR         build output and work files    (build/)
  --review DIR        regenerated pictures to look at    (review/)'''


def _set(root=PROJECT, rom=None, translation=None, extracted=None, build=None, review=None):
    global ROOT, ROM_DIR, ROM, TRANSLATION, SCRIPT, TEXT, FILL, GLOSSARY, GRAPHICS_CSV, RENDERS_JSON
    global RENDERED, APPROVED, HANDMADE, EXTRACTED, BUILD, WORK, RELEASE, REVIEW
    global ORIGINAL_IMAGES, ENGLISH_IMAGES, COMPARE, CONTACT_SHEETS, EDIT_REFS, SCREENSHOTS, DOCS
    ROOT = Path(root)

    rom = Path(rom) if rom else ROOT / 'rom'
    if rom.is_file() or rom.suffix.lower() in ('.bin', '.iso', '.img'):
        ROM_DIR, ROM = rom.parent, rom
    else:
        ROM_DIR = rom
        found = sorted(p for p in rom.glob('*') if p.suffix.lower() in ('.bin', '.iso', '.img')) \
            if rom.is_dir() else []
        ROM = rom / ORIGINAL_NAME if (rom / ORIGINAL_NAME).exists() or len(found) != 1 else found[0]

    TRANSLATION = Path(translation) if translation else ROOT / 'translation'
    SCRIPT = TRANSLATION / 'script'
    TEXT = TRANSLATION / 'text'
    FILL = TRANSLATION / 'fill'
    GLOSSARY = TRANSLATION / 'glossary.csv'
    GRAPHICS_CSV = TRANSLATION / 'graphics.csv'
    RENDERS_JSON = TRANSLATION / 'renders.json'
    RENDERED = TRANSLATION / 'images-rendered'
    APPROVED = TRANSLATION / 'images-approved'
    HANDMADE = TRANSLATION / 'images-handmade'

    EXTRACTED = Path(extracted) if extracted else ROOT / 'extracted'
    BUILD = Path(build) if build else ROOT / 'build'
    WORK = BUILD / 'work'
    RELEASE = ROOT / 'release'

    REVIEW = Path(review) if review else ROOT / 'review'
    ORIGINAL_IMAGES = REVIEW / 'images-original'
    ENGLISH_IMAGES = REVIEW / 'images-english'
    COMPARE = REVIEW / 'compare'
    CONTACT_SHEETS = REVIEW / 'contact-sheets'
    EDIT_REFS = REVIEW / 'edit'

    SCREENSHOTS = ROOT / 'screenshots'
    DOCS = ROOT / 'docs'


_set()


def configure(argv):
    """Apply the folder options found in argv; returns the remaining arguments for the tool itself."""
    ap = argparse.ArgumentParser(add_help=False, allow_abbrev=False)
    for opt in ('root', 'rom', 'translation', 'extracted', 'build', 'review'):
        ap.add_argument(f'--{opt}')
    args, rest = ap.parse_known_args(argv)
    _set(**{k: v for k, v in vars(args).items() if v})
    return rest


def show(p):
    """A path for messages: relative to the current directory when it is inside it."""
    return _show(str(p), os.getcwd())


@functools.lru_cache(maxsize=None)
def _show(p, cwd):   # cached: resolve() stats every folder - slow on a Windows drive under WSL, and
    p = Path(p)      # text steps call this once per string (97 s of a 3-minute build, uncached)
    try:
        return str(p.resolve().relative_to(Path(cwd)))
    except ValueError:
        return str(p)
